"""Identify port/board sources and flags without changing upstream dependencies.

This deliberately is not the kernel binary hash, an upstream-dependency hash or
an attestation of hardware testing. Use the report's scope when comparing IDs.
"""
import argparse
import hashlib
import json
from pathlib import Path

SUFFIXES = {'.c', '.h', '.cpp', '.S', '.s', '.mk', '.py'}


def linked(path):
    return path.is_symlink() or bool(getattr(path, 'is_junction', lambda: False)())


def source_files(root):
    if linked(root):
        raise ValueError('linked source root is not allowed')
    if not root.is_dir():
        raise ValueError('source directory is missing')
    for path in sorted(root.iterdir(), key=lambda p: p.name):
        if linked(path):
            raise ValueError('linked source path is not allowed: ' + path.name)
        if path.name == '__pycache__':
            continue
        if path.is_dir():
            yield from source_files(path)
        elif path.is_file() and (path.suffix in SUFFIXES or path.name == 'Makefile'):
            yield path


def collect_identity(port_dir, board_dir, flags):
    files = []
    for label, root in (('port', Path(port_dir)), ('board', Path(board_dir))):
        for path in source_files(root):
            files.append({'path': label + '/' + path.relative_to(root).as_posix(),
                          'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    files.sort(key=lambda entry: entry['path'])
    payload = {'schema': 1, 'scope': 'port-and-board-source', 'files': files,
               'flags': list(flags)}
    data = json.dumps(payload, sort_keys=True, separators=(',', ':')).encode('utf-8')
    return dict(payload, sha256=hashlib.sha256(data).hexdigest())


def write_changed(path, text):
    path = Path(path)
    content = text.encode('utf-8')
    if path.is_file() and path.read_bytes() == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--port', required=True)
    parser.add_argument('--board', required=True)
    parser.add_argument('--header', required=True)
    parser.add_argument('--report', required=True)
    parser.add_argument('--flag', action='append', default=[])
    args = parser.parse_args()
    port_input, board_input = Path(args.port).absolute(), Path(args.board).absolute()
    if any(linked(p) for root in (port_input, board_input) for p in (root, *root.parents)):
        parser.error('linked source path is not allowed')
    port, board = port_input.resolve(), board_input.resolve()
    # Outputs must not enter the input trees (nor be linked files) and change IDs.
    for output in (Path(args.header).absolute(), Path(args.report).absolute()):
        if linked(output) or any(linked(p) for p in output.parents):
            parser.error('linked output path is not allowed')
        normalized = output.resolve()
        if normalized == port or normalized == board or port in normalized.parents or board in normalized.parents:
            parser.error('outputs must be outside source input trees')
    identity = collect_identity(port, board, args.flag)
    header = ('// Generated by the port build identity tool.\n'
              '#ifndef MPYNN_BUILD_IDENTITY_H\n#define MPYNN_BUILD_IDENTITY_H\n'
              '#define MPYNN_PORT_BUILD_ID "' + identity['sha256'] + '"\n#endif\n')
    write_changed(args.header, header)
    write_changed(args.report, json.dumps(identity, indent=2, sort_keys=True) + '\n')


if __name__ == '__main__':
    main()
